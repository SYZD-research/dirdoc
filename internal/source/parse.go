// Doc is a parsed source file. Pointer fields are nil when the key was absent, which --merge relies on.
type Doc struct {
	Kind     model.Kind
	File     string
	Summary  *string
	Tree     *model.TreeNode
	HasTree  bool
	Target   *string // JSON input only
	Sections map[string][]*Entry
	Extra    model.Extra

	TopLines  map[string]int
	TreeLine  int // file line of the first line of the tree text
	NodeLines map[*model.TreeNode]int
}

// Entry is one [[dsd]], [[types]], [[functions]] or [[variables]] table.
type Entry struct {
	Section  string
	Index    int
	Line     int
	KeyLines map[string]int
	ID       *string
	Name     *string
	Summary  *string
	Document *string
	Delete   bool
	Extra    model.Extra
}

// Str returns *p, or "" when p is nil.
func Str(p *string) string {
	if p == nil {
		return ""
	}
	return *p
}

var topKeys = map[model.Kind][]string{
	model.KindDSD: {"summary", "tree", model.SectionDSD},
	model.KindPFD: {"summary", model.SectionTypes, model.SectionFunctions, model.SectionVariables},
}

var entryKeys = map[string][]string{
	model.SectionDSD:       {"id", "name", "document", "delete"},
	model.SectionTypes:     {"id", "name", "summary", "document", "delete"},
	model.SectionFunctions: {"id", "name", "summary", "document", "delete"},
	model.SectionVariables: {"id", "name", "summary", "delete"},
}

// IsJSON reports whether a source should be read as JSON: a .json name or content starting with "{".
func IsJSON(name string, data []byte) bool {
	if strings.HasSuffix(strings.ToLower(name), ".json") {
		return true
	}
	t := bytes.TrimLeft(data, " \t\r\n")
	return len(t) > 0 && t[0] == '{'
}

// Parse reads a TOML or JSON source for a document of the given kind.
func Parse(data []byte, file string, kind model.Kind) (*Doc, diag.List) {
	var l diag.List
	data = bytes.TrimPrefix(data, []byte("\xef\xbb\xbf"))
	jsonInput := IsJSON(file, data)
	var m map[string]any
	lay := &layout{top: map[string]keyPos{}, tables: map[string][]*tableLayout{}}
	if jsonInput {
		dec := json.NewDecoder(bytes.NewReader(data))
		dec.UseNumber()
		if err := dec.Decode(&m); err != nil {
			d := l.Errorf(diag.CodeParse, "", "invalid JSON: %v", err)
			d.File = file
			var se *json.SyntaxError
			if errors.As(err, &se) {
				d.Line = 1 + bytes.Count(data[:min(int(se.Offset), len(data))], []byte("\n"))
			}
			return nil, l
		}
	} else {
		if err := toml.Unmarshal(data, &m); err != nil {
			d := l.Errorf(diag.CodeParse, "", "invalid TOML: %v", err)
			d.File = file
			var de *toml.DecodeError
			if errors.As(err, &de) {
				d.Line, _ = de.Position()
			}
			return nil, l
		}
		lay = scanLayout(data)
	}
	if m == nil {
		d := l.Errorf(diag.CodeParse, "", "the source must be a table (TOML) or an object (JSON)")
		d.File = file
		return nil, l
	}
	p := &parser{
		doc:  &Doc{Kind: kind, File: file, Sections: map[string][]*Entry{}, TopLines: map[string]int{}},
		l:    &l,
		lay:  lay,
		json: jsonInput,
	}
	p.top(m)
	return p.doc, l
}

type parser struct {
	doc  *Doc
	l    *diag.List
	lay  *layout
	json bool
}

func (p *parser) fail(line int, code, format string, args ...any) {
	d := p.l.Errorf(code, "", format, args...)
	d.File, d.Line = p.doc.File, line
}

func (p *parser) warn(line int, code, format string, args ...any) {
	d := p.l.Warnf(code, "", format, args...)
	d.File, d.Line = p.doc.File, line
}

func (p *parser) top(m map[string]any) {
	kind := p.doc.Kind
	other := model.KindPFD
	if kind == model.KindPFD {
		other = model.KindDSD
	}
	for _, k := range sortedKeys(m) {
		v := m[k]
		pos := p.lay.top[k]
		p.doc.TopLines[k] = pos.line
		switch {
		case k == "kind":
			s, ok := v.(string)
			if !ok || (s != "dsd" && s != "pfd") {
				p.fail(pos.line, diag.CodeParse, `kind must be "dsd" or "pfd"`)
			} else if s != kind.String() {
				p.fail(pos.line, diag.CodeParse, "this source is for a %s, but the target is a %s", s, describe(kind))
			}
		case k == "summary":
			if s, ok := p.str(k, v, pos.line); ok {
				p.doc.Summary = &s
			}
		case k == "tree" && kind == model.KindDSD:
			p.tree(v, pos)
		case contains(topKeys[kind], k):
			p.section(k, v, pos.line)
		case k == "overview" || k == "target_hash":
			p.warn(pos.line, diag.CodeSourceIgnored, "%s is generated by compile; the value in the source is ignored", k)
		case p.json && (k == "format" || k == "version" || k == "target"):
			p.jsonHeader(k, v, pos.line)
		case strings.HasPrefix(k, "x-"):
			p.extra(&p.doc.Extra, k, v, pos.line)
		case contains(topKeys[other], k):
			p.fail(pos.line, diag.CodeParse, "%s is only valid for a %s, but the target is a %s", k, describe(other), describe(kind))
		default:
			p.fail(pos.line, diag.CodeParse, "unknown key %q%s", k, suggest(k, append(topKeys[kind], "kind")))
		}
	}
}

func describe(k model.Kind) string {
	if k == model.KindDSD {
		return "directory (DSD)"
	}
	return "file (PFD)"
}

func (p *parser) jsonHeader(k string, v any, line int) {
	switch k {
	case "format":
		want := model.FormatDSD
		if p.doc.Kind == model.KindPFD {
			want = model.FormatPFD
		}
		if s, _ := v.(string); s != want {
			p.fail(line, diag.CodeParse, "format must be %q for this target", want)
		}
	case "version":
		if n, _ := v.(json.Number); n.String() != fmt.Sprint(model.Version) {
			p.fail(line, diag.CodeVersion, "unsupported version %v (this dirdoc supports %d)", v, model.Version)
		}
	case "target":
		if s, ok := p.str(k, v, line); ok {
			p.doc.Target = &s
		}
	}
}

func (p *parser) str(key string, v any, line int) (string, bool) {
	s, ok := v.(string)
	if !ok {
		p.fail(line, diag.CodeParse, "%s must be a string", key)
	}
	return s, ok
}

func (p *parser) tree(v any, pos keyPos) {
	switch t := v.(type) {
	case string:
		root, lines, issues := ParseTree(t)
		for _, is := range issues {
			line := 0
			if pos.content > 0 {
				line = pos.content + is.Line - 1
			}
			p.fail(line, diag.CodeTreeSyntax, "tree: %s", is.Message)
		}
		p.doc.Tree, p.doc.HasTree = root, true
		p.doc.TreeLine, p.doc.NodeLines = pos.content, lines
	case map[string]any:
		raw, err := model.Marshal(t)
		node := new(model.TreeNode)
		if err == nil {
			err = json.Unmarshal(raw, node)
		}
		if err != nil {
			p.fail(pos.line, diag.CodeParse, "tree: %v", err)
			return
		}
		p.doc.Tree, p.doc.HasTree = node, true
	default:
		p.fail(pos.line, diag.CodeParse, "tree must be a string in the tree notation")
	}
}

func tables(v any) ([]map[string]any, bool) {
	switch t := v.(type) {
	case []map[string]any:
		return t, true
	case []any:
		out := make([]map[string]any, 0, len(t))
		for _, item := range t {
			m, ok := item.(map[string]any)
			if !ok {
				return nil, false
			}
			out = append(out, m)
		}
		return out, true
	}
	return nil, false
}

func (p *parser) section(name string, v any, line int) {
	items, ok := tables(v)
	if !ok {
		p.fail(line, diag.CodeParse, "%s must be an array of tables, written [[%s]]", name, name)
		return
	}
	allowed := entryKeys[name]
	for i, item := range items {
		tl := p.lay.entry(name, i)
		e := &Entry{Section: name, Index: i, Line: tl.line, KeyLines: map[string]int{}}
		for k, kp := range tl.keys {
			e.KeyLines[k] = kp.line
		}
		lineOf := func(k string) int {
			if ln := e.KeyLines[k]; ln > 0 {
				return ln
			}
			return e.Line
		}
		for _, k := range sortedKeys(item) {
			val := item[k]
			switch {
			case k == "delete" && contains(allowed, k):
				b, ok := val.(bool)
				if !ok {
					p.fail(lineOf(k), diag.CodeParse, "%s[%d].delete must be true or false", name, i)
				}
				e.Delete = b
			case contains(allowed, k):
				s, ok := p.str(fmt.Sprintf("%s[%d].%s", name, i, k), val, lineOf(k))
				if !ok {
					continue
				}
				switch k {
				case "id":
					e.ID = &s
				case "name":
					e.Name = &s
				case "summary":
					e.Summary = &s
				case "document":
					e.Document = &s
				}
			case strings.HasPrefix(k, "x-"):
				p.extra(&e.Extra, k, val, lineOf(k))
			case k == "document" && name == model.SectionVariables:
				p.fail(lineOf(k), diag.CodeParse, "variables have no document; describe the variable in its summary")
			case k == "summary" && name == model.SectionDSD:
				p.fail(lineOf(k), diag.CodeParse, "dsd entries have no summary; use the tree note or the document")
			default:
				p.fail(lineOf(k), diag.CodeParse, "unknown key %q in [[%s]]%s", k, name, suggest(k, allowed))
			}
		}
		p.doc.Sections[name] = append(p.doc.Sections[name], e)
	}
}

func (p *parser) extra(dst *model.Extra, k string, v any, line int) {
	raw, err := model.Marshal(v)
	if err != nil {
		p.fail(line, diag.CodeParse, "%s: %v", k, err)
		return
	}
	if *dst == nil {
		*dst = model.Extra{}
	}
	(*dst)[k] = raw
}

func sortedKeys(m map[string]any) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func contains(list []string, s string) bool {
	for _, v := range list {
		if v == s {
			return true
		}
	}
	return false
}

// suggest returns a "did you mean" hint for keys within two edits of a known key.
func suggest(key string, known []string) string {
	best, bestDist := "", 3
	for _, k := range known {
		if d := editDistance(key, k); d < bestDist {
			best, bestDist = k, d
		}
	}
	if best == "" {
		return ""
	}
	return fmt.Sprintf(" (did you mean %q?)", best)
}

func editDistance(a, b string) int {
	ra, rb := []rune(a), []rune(b)
	prev := make([]int, len(rb)+1)
	cur := make([]int, len(rb)+1)
	for j := range prev {
		prev[j] = j
	}
	for i := 1; i <= len(ra); i++ {
		cur[0] = i
		for j := 1; j <= len(rb); j++ {
			cost := 1
			if ra[i-1] == rb[j-1] {
				cost = 0
			}
			cur[j] = min(prev[j]+1, cur[j-1]+1, prev[j-1]+cost)
		}
		prev, cur = cur, prev
	}
	return prev[len(rb)]
}
