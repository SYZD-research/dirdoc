// ErrNotStored reports TOML without a format key: a source, such as the one the merge driver leaves
// in place of a document it could not merge, rather than a stored document.
var ErrNotStored = errors.New("the TOML is a source, not a stored document (it has no format key)")

// SyntaxError reports text that is not valid TOML.
type SyntaxError struct {
	Line int // 0 when unknown
	Err  error
}

func (e *SyntaxError) Error() string {
	if e.Line > 0 {
		return fmt.Sprintf("invalid TOML (line %d): %v", e.Line, e.Err)
	}
	return "invalid TOML: " + e.Err.Error()
}

func (e *SyntaxError) Unwrap() error { return e.Err }

// EmitStored prints a document as the TOML that storage.format = "toml" stores (design §5.4): the
// source export prints, with the format, version and target, every unknown field, and a [generated]
// table holding the target_hash and the symbols of the code. The overview is left out; ParseStored
// rebuilds it from the entries and the symbols. A document TOML cannot hold, such as one with a null
// value, is an error, so that no file is written that reads back differently.
func EmitStored(d *model.DSD, p *model.PFD) (string, error) {
	w := &tomlWriter{stored: true}
	var doc any
	if d != nil {
		if rel, ok := treeExtra(d.Tree); ok {
			return "", fmt.Errorf("cannot store as TOML: the tree node %s has fields the tree notation cannot hold", rel)
		}
		w.storedDSD(d)
		doc = d
	} else {
		c, err := model.ClonePFD(p)
		if err != nil {
			return "", err
		}
		model.Reindex(c) // what ParseStored rebuilds
		w.storedPFD(c)
		doc = c
	}
	if w.err != nil {
		return "", fmt.Errorf("cannot store as TOML: %w", w.err)
	}
	text := w.String()
	want, err := model.Marshal(doc)
	if err != nil {
		return "", err
	}
	// Whatever does not survive the round trip (a number TOML reads differently, a name the tree
	// notation cannot write) must fail here rather than leave a file that reads differently.
	_, d2, p2, err := ParseStored([]byte(text))
	var got []byte
	if err == nil {
		if d2 != nil {
			got, err = model.Marshal(d2)
		} else {
			got, err = model.Marshal(p2)
		}
	}
	if err != nil || !sameValue(want, got) {
		return "", errors.New("cannot store as TOML: the document holds values that TOML or the tree notation cannot keep as they are")
	}
	return text, nil
}

func (w *tomlWriter) storedDSD(d *model.DSD) {
	w.comment("dirdoc dsd")
	w.kv("format", model.FormatDSD)
	w.raw("version = " + strconv.Itoa(model.Version))
	if d.Summary != "" {
		w.kv("summary", d.Summary)
	}
	if d.Tree != nil {
		w.blank()
		w.raw("tree = " + multiline(FormatTree(d.Tree, LinkAnnotator)))
	}
	w.extras(nil, "", "", d.Extra)
	for _, e := range d.Entries {
		w.blank()
		w.dsdEntry(nil, e)
	}
}

func (w *tomlWriter) storedPFD(p *model.PFD) {
	w.comment("dirdoc pfd: " + p.Target)
	w.kv("format", model.FormatPFD)
	w.raw("version = " + strconv.Itoa(model.Version))
	w.kv("target", p.Target)
	if p.Summary != "" {
		w.kv("summary", p.Summary)
	}
	w.extras(nil, "", "", p.Extra)
	for _, sec := range model.PFDSections {
		for _, e := range p.Section(sec) {
			w.blank()
			w.entry(nil, sec, e)
		}
	}
	syms := model.OverviewSymbols(p.Overview)
	if p.TargetHash == "" && syms == nil {
		return
	}
	w.blank()
	w.comment("Generated by dirdoc compile and dirdoc touch from " + p.Target + "; do not edit.")
	w.raw("[generated]")
	if p.TargetHash != "" {
		w.kv("target_hash", p.TargetHash)
	}
	switch {
	case syms == nil: // the file was not analyzed
	case len(syms) == 0:
		w.raw("symbols = []")
	default:
		sort.SliceStable(syms, func(i, j int) bool { return syms[i].Line < syms[j].Line })
		w.raw("symbols = [")
		for _, s := range syms {
			w.raw(fmt.Sprintf("  { id = %s, kind = %s, line = %d, signature = %s },",
				basicString(s.ID), basicString(s.Kind), s.Line, basicString(s.Signature)))
		}
		w.raw("]")
	}
}

// treeExtra returns the path of a node with unknown fields, which the tree notation cannot write.
func treeExtra(root *model.TreeNode) (string, bool) {
	if root == nil {
		return "", false
	}
	found := ""
	root.Walk(func(n *model.TreeNode, rel string) {
		if found == "" && len(n.Extra) > 0 {
			found = "./" + rel
		}
	})
	return found, found != ""
}

// sameValue reports whether two JSON texts hold the same value, so that 1.0 and 1 are equal.
func sameValue(a, b []byte) bool {
	var va, vb any
	if json.Unmarshal(a, &va) != nil || json.Unmarshal(b, &vb) != nil {
		return false
	}
	return reflect.DeepEqual(va, vb)
}

// ParseStored reads the TOML that EmitStored prints. Unknown fields are kept, keys of [generated]
// other than symbols are read like top-level fields, and an entry without an id gets the one derived
// from its name, so that a hand-edited file reads as its source would. It returns ErrNotStored for
// TOML without a format key, and a *SyntaxError for text that is not TOML.
func ParseStored(data []byte) (model.Kind, *model.DSD, *model.PFD, error) {
	data = bytes.TrimPrefix(data, []byte("\xef\xbb\xbf"))
	var m map[string]any
	if err := toml.Unmarshal(data, &m); err != nil {
		se := &SyntaxError{Err: err}
		var de *toml.DecodeError
		if errors.As(err, &de) {
			se.Line, _ = de.Position()
		}
		return 0, nil, nil, se
	}
	if _, ok := m["format"]; !ok {
		return 0, nil, nil, ErrNotStored
	}
	var syms []model.Symbol
	if g, ok := m["generated"]; ok {
		delete(m, "generated")
		gm, ok := g.(map[string]any)
		if !ok {
			return 0, nil, nil, errors.New("generated must be a table")
		}
		for k, v := range gm {
			if k == "symbols" {
				var err error
				if syms, err = storedSymbols(v); err != nil {
					return 0, nil, nil, err
				}
				continue
			}
			if _, dup := m[k]; dup {
				return 0, nil, nil, fmt.Errorf("%s is set both at the top and in [generated]", k)
			}
			m[k] = v // target_hash, and what a newer dirdoc generates
		}
	}
	storedText(m, "summary")
	if t, ok := m["tree"]; ok {
		s, ok := t.(string)
		if !ok {
			return 0, nil, nil, errors.New("tree must be a string in the tree notation")
		}
		root, _, issues := ParseTree(lf(s))
		if len(issues) > 0 {
			return 0, nil, nil, fmt.Errorf("tree, line %d: %s", issues[0].Line, issues[0].Message)
		}
		m["tree"] = root
	}
	for _, sec := range append([]string{model.SectionDSD}, model.PFDSections...) {
		v, ok := m[sec]
		if !ok {
			continue
		}
		items, ok := tables(v)
		if !ok {
			return 0, nil, nil, fmt.Errorf("%s must be an array of tables, written [[%s]]", sec, sec)
		}
		for _, it := range items {
			for _, k := range []string{"name", "summary", "document"} {
				storedText(it, k)
			}
			if _, ok := it["id"]; !ok {
				if name, ok := it["name"].(string); ok {
					if id, ok := model.DeriveID(name); ok {
						it["id"] = id
					}
				}
			}
		}
		m[sec] = items
	}
	js, err := model.Marshal(m)
	if err != nil {
		return 0, nil, nil, err
	}
	kind, d, p, err := model.Decode(js)
	if err != nil {
		return 0, nil, nil, err
	}
	if p != nil {
		p.Overview = model.BuildOverview(p)
		model.AnnotateOverview(&p.Overview, syms)
	}
	return kind, d, p, nil
}

// storedText normalizes the line endings of a text field and drops the newline EmitStored writes
// before the closing quotes of a multi-line string.
func storedText(m map[string]any, key string) {
	if s, ok := m[key].(string); ok {
		m[key] = strings.TrimSuffix(lf(s), "\n")
	}
}

// lf converts CRLF and CR line endings to LF.
func lf(s string) string {
	if !strings.Contains(s, "\r") {
		return s
	}
	return strings.ReplaceAll(strings.ReplaceAll(s, "\r\n", "\n"), "\r", "\n")
}

func storedSymbols(v any) ([]model.Symbol, error) {
	items, ok := tables(v)
	if !ok {
		return nil, errors.New("generated.symbols must be an array of tables")
	}
	syms := make([]model.Symbol, 0, len(items)) // [] (analyzed) stays apart from nil (not analyzed)
	for i, it := range items {
		var s model.Symbol
		js, err := model.Marshal(it)
		if err == nil {
			err = json.Unmarshal(js, &s)
		}
		if err != nil {
			return nil, fmt.Errorf("generated.symbols[%d]: %v", i, err)
		}
		syms = append(syms, s)
	}
	return syms, nil
}
